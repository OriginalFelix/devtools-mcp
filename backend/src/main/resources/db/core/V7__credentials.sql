-- Zugangsdaten je Benutzer (Modul „Zugangsdaten“ der Desktop-App, wie beim Git Credential Manager): Token bzw.
-- Passwort je Server-URL. secret ist mit dem Schlüssel aus secret.key verschlüsselt (AES-GCM); sort_order hält die
-- Reihenfolge, die bei gleich gut passenden Einträgen entscheidet.
CREATE TABLE credential (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                   NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    sort_order  INT                      NOT NULL,
    name        VARCHAR(64)              NOT NULL,
    url         VARCHAR(1000)            NOT NULL,
    username    VARCHAR(200),
    secret      VARCHAR(8000)            NOT NULL,
    description VARCHAR(500),
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_credential_user_name UNIQUE (user_id, name)
);
